# Formula Injection Mitigation
# ---------------------------------------------------------------------------

FORMULA_TRIGGERS = ("=", "+", "-", "@")


def sanitize_for_spreadsheet(val: Any) -> Any:
    """
    Spreadsheet formula-injection mitigation for untrusted strings.
    - If val is typed numeric (int, float) or bool or None: left untouched.
    - If val is a string starting with '=', '+', '-', '@':
      checks if it's a legitimate number string (e.g. "-150.5").
      If it is not a valid number, prepends single quote (') to neutralize execution.
    """
    if isinstance(val, (int, float, bool)) or val is None:
        return val
    if isinstance(val, str):
        s = val.strip()
        if not s:
            return val
        if s[0] in FORMULA_TRIGGERS:
            try:
                # Check if it is a pure numeric representation like "-42" or "+3.14"
                float(s)
                return val
            except ValueError:
                # Untrusted formula string
                return f"'{val}"
    return val


