def prepare_dashboard_export_data(
    db: Session,
    dashboard_id: str,
    filters: Optional[Dict[str, Any]] = None,
    storage: Optional[StorageBackend] = None,
) -> Dict[str, Any]:
    """
    Renders the exact verified dashboard specification from Parquet datasets
    and extracts all required metadata, widgets, tables, and warnings for export.
    """
    if storage is None:
        from app.storage import get_storage_backend
        storage = get_storage_backend()

    dash_repo = DashboardRepository(db)
    dash = dash_repo.get(dashboard_id)
    if not dash:
        raise ValueError(f"Dashboard '{dashboard_id}' not found.")

    upload_repo = UploadRepository(db)
    upload = upload_repo.get(dash.upload_id) if dash.upload_id else None

    dataset_repo = DatasetRepository(db)
    datasets = dataset_repo.list_by_upload(dash.upload_id) if dash.upload_id else []
    ds_lookup = {
        str(d.id): d
        for d in datasets
        if d.parquet_storage_key and storage.object_exists(d.parquet_storage_key)
    }

    spec_dict = dash.spec or {}
    raw_widgets = spec_dict.get("widgets", [])
    sot_confirmed = spec_dict.get("source_of_truth_confirmed", False)

    # Global filter conversion
    filter_obj = None
    if filters:
        filter_obj = GlobalFilterInput(
            period=filters.get("period"),
            model=filters.get("model"),
            defect=filters.get("defect"),
            action_owner=filters.get("action_owner"),
            action_status=filters.get("action_status"),
        )

    rendered_widgets: List[Dict[str, Any]] = []
    widget_warnings: List[str] = list(spec_dict.get("global_warnings", []))

    for w_dict in raw_widgets:
        try:
            widget = ManufacturingWidgetSpec.model_validate(w_dict)
            target_ds = ds_lookup.get(widget.dataset_id)
            if target_ds:
                rendered = execute_manufacturing_widget(
                    widget=widget,
                    storage=storage,
                    dataset=target_ds,
                    filters=filter_obj,
                    source_of_truth_confirmed=sot_confirmed,
                )
                rendered_widgets.append(rendered)
            else:
                msg = f"Source dataset '{widget.dataset_id}' for widget '{widget.title}' is unavailable or missing Parquet file."
                widget_warnings.append(msg)
                rendered_widgets.append({
                    "widget_id": widget.widget_id,
                    "widget_type": widget.widget_type,
                    "title": widget.title,
                    "error": msg,
                    "warnings": [msg],
                    "provenance": widget.provenance.model_dump(),
                })
        except Exception as exc:
            logger.warning(f"Failed to render widget '{w_dict.get('widget_id')}': {exc}")
            widget_warnings.append(f"Widget calculation error: {str(exc)}")

    # Check SOT reconciliation conflict
    conflict_warning = None
    if not sot_confirmed:
        conflict_warning = (
            "SOURCE OF TRUTH RECONCILIATION CONFLICT: January 2026 production denominator "
            "differs between Target 2026 (37,111) and Paynter 2026 (46,816). Authoritative PPM "
            "calculation is unconfirmed and withheld per quality governance policy."
        )

    # Extract tabular data from datasets (up to 5,000 rows each for export)
    dataset_tables = []
    for d in datasets:
        if d.parquet_storage_key and storage.object_exists(d.parquet_storage_key):
            try:
                parquet_bytes = storage.get_object(d.parquet_storage_key)
                df = pd.read_parquet(io.BytesIO(parquet_bytes))
                # Bounded row count for export memory safety
                max_export_rows = 10000
                if len(df) > max_export_rows:
                    df = df.iloc[:max_export_rows]
                dataset_tables.append({
                    "dataset_id": str(d.id),
                    "sheet_name": d.sheet_name or "Sheet1",
                    "cell_range": d.cell_range or "A1",
                    "columns": list(df.columns),
                    "rows": df.to_dict(orient="records"),
                    "row_count": len(df),
                })
            except Exception as e:
                logger.warning(f"Could not load parquet for dataset {d.id}: {e}")

    now_utc = dt.datetime.now(dt.timezone.utc)
    return {
        "dashboard_id": str(dash.id),
        "title": dash.title or "Manufacturing Quality Report",
        "upload_id": str(dash.upload_id) if dash.upload_id else "",
        "source_filename": upload.original_filename if upload else "Manufacturing_Quality_2026.xlsx",
        "generated_at": now_utc.strftime("%Y-%m-%d %H:%M:%S UTC"),
        "created_at": dash.created_at.strftime("%Y-%m-%d %H:%M:%S") if dash.created_at else "",
        "filters": filters or {},
        "sot_confirmed": sot_confirmed,
        "conflict_warning": conflict_warning,
        "reconciliation": spec_dict.get("reconciliation", {}),
        "widgets": rendered_widgets,
        "raw_specs": raw_widgets,
        "global_warnings": list(dict.fromkeys(widget_warnings)),
        "dataset_tables": dataset_tables,
    }


