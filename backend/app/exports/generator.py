def generate_csv_export(
    data: Dict[str, Any],
    output_path: str,
    options: Optional[Dict[str, Any]] = None,
) -> int:
    """
    Generates a UTF-8 with BOM (utf-8-sig) CSV export with formula injection
    protection. Exports the primary normalized dataset or summary metrics table.
    """
    options = options or {}
    export_mode = options.get("export_mode", "normalized")  # 'normalized' or 'summary'

    with open(output_path, mode="w", newline="", encoding="utf-8-sig") as f:
        writer = csv.writer(f, quoting=csv.QUOTE_MINIMAL)

        # File header notice
        writer.writerow(["# Title:", data["title"]])
        writer.writerow(["# Generated At:", data["generated_at"]])
        writer.writerow(["# Source:", data["source_filename"]])
        if data.get("conflict_warning"):
            writer.writerow(["# RECONCILIATION WARNING:", data["conflict_warning"]])
        writer.writerow([])

        dataset_tables = data.get("dataset_tables", [])
        if export_mode == "normalized" and dataset_tables:
            # Export primary normalized table
            primary_table = dataset_tables[0]
            cols = primary_table.get("columns", [])
            writer.writerow(cols)

            for r_dict in primary_table.get("rows", []):
                row_vals = []
                for c in cols:
                    val = r_dict.get(c)
                    sanitized = sanitize_for_spreadsheet(val)
                    row_vals.append("" if sanitized is None else str(sanitized))
                writer.writerow(row_vals)
        else:
            # Export summary metrics (e.g. PPM Trend / Pareto)
            writer.writerow(["Metric_Type", "Period_Or_Defect", "Actual_Value", "Target_Value", "Variance_Or_CumPct", "Status"])
            for w in data.get("widgets", []):
                w_type = w.get("widget_type")
                if w_type == "ppm_trend_target":
                    for pt in w.get("data_points", []):
                        writer.writerow([
                            "PPM_Trend",
                            pt.get("period", ""),
                            pt.get("actual_ppm", "N/A"),
                            pt.get("target_ppm", 2000),
                            pt.get("variance", "N/A"),
                            "EXCEEDED" if pt.get("is_exceeded") else "WITHIN_TARGET",
                        ])
                elif w_type == "defect_pareto":
                    for item in w.get("items", []):
                        writer.writerow([
                            "Defect_Pareto",
                            sanitize_for_spreadsheet(item.get("defect", "")),
                            item.get("rejections", 0),
                            "",
                            item.get("cumulative_percent", 0),
                            "CONFIRMED",
                        ])

    return os.path.getsize(output_path)


