def generate_excel_export(
    data: Dict[str, Any],
    output_path: str,
    options: Optional[Dict[str, Any]] = None,
) -> int:
    """
    Generates a structured, multi-sheet Excel report with:
    - Summary Sheet: Executive KPI summary, active filters, SOT warnings, and widget tables.
    - Dashboard Spec Sheet: Technical specification and metric provenance.
    - Normalized Dataset Sheet(s): Sanitized table rows with formula-injection protection.
    """
    workbook = xlsxwriter.Workbook(output_path, {"nan_inf_to_errors": True})

    # Color palette & styles
    header_fmt = workbook.add_format({
        "bold": True,
        "bg_color": "#0f172a",
        "font_color": "#ffffff",
        "border": 1,
        "font_size": 10,
        "align": "center",
        "valign": "vcenter",
    })
    sub_header_fmt = workbook.add_format({
        "bold": True,
        "bg_color": "#1e293b",
        "font_color": "#38bdf8",
        "font_size": 11,
        "valign": "vcenter",
    })
    title_fmt = workbook.add_format({
        "bold": True,
        "font_size": 16,
        "font_color": "#0f172a",
    })
    meta_label_fmt = workbook.add_format({
        "bold": True,
        "font_size": 9,
        "font_color": "#475569",
    })
    meta_val_fmt = workbook.add_format({
        "font_size": 9,
        "font_color": "#0f172a",
    })
    warning_box_fmt = workbook.add_format({
        "bold": True,
        "bg_color": "#fee2e2",
        "font_color": "#991b1b",
        "border": 1,
        "text_wrap": True,
        "font_size": 9,
    })
    cell_fmt = workbook.add_format({
        "border": 1,
        "border_color": "#cbd5e1",
        "font_size": 9,
    })
    num_fmt = workbook.add_format({
        "border": 1,
        "border_color": "#cbd5e1",
        "font_size": 9,
        "num_format": "#,##0",
        "align": "right",
    })
    pct_fmt = workbook.add_format({
        "border": 1,
        "border_color": "#cbd5e1",
        "font_size": 9,
        "num_format": "0.0%",
        "align": "right",
    })

    # --- Sheet 1: Summary ---
    ws_sum = workbook.add_worksheet("Summary")
    ws_sum.set_tab_color("#0284c7")
    ws_sum.set_column(0, 0, 22)
    ws_sum.set_column(1, 1, 26)
    ws_sum.set_column(2, 5, 18)

    ws_sum.write(0, 0, data["title"], title_fmt)
    ws_sum.write(1, 0, "Executive Manufacturing Quality Summary", meta_val_fmt)

    # Metadata block
    ws_sum.write(3, 0, "Generated At:", meta_label_fmt)
    ws_sum.write(3, 1, data["generated_at"], meta_val_fmt)
    ws_sum.write(4, 0, "Source Workbook:", meta_label_fmt)
    ws_sum.write(4, 1, data["source_filename"], meta_val_fmt)
    ws_sum.write(5, 0, "Active Filters:", meta_label_fmt)
    active_filters_str = ", ".join(f"{k}: {v}" for k, v in data.get("filters", {}).items() if v) or "None (Full Dataset)"
    ws_sum.write(5, 1, active_filters_str, meta_val_fmt)
    ws_sum.write(6, 0, "Source of Truth Status:", meta_label_fmt)
    ws_sum.write(6, 1, "Confirmed" if data["sot_confirmed"] else "Unconfirmed Conflict", meta_val_fmt)

    curr_row = 8
    # Warning Banner if Conflict
    if data.get("conflict_warning"):
        ws_sum.merge_range(curr_row, 0, curr_row + 1, 5, data["conflict_warning"], warning_box_fmt)
        curr_row += 3

    # Render Widget Summaries
    for w in data.get("widgets", []):
        w_type = w.get("widget_type")
        w_title = w.get("title", "Widget")

        ws_sum.write(curr_row, 0, f"Section: {w_title}", sub_header_fmt)
        curr_row += 1

        if w_type == "ppm_trend_target":
            ws_sum.write_row(curr_row, 0, ["Month", "Actual PPM", "Target PPM", "Variance", "Target Status"], header_fmt)
            curr_row += 1
            for pt in w.get("data_points", []):
                period = pt.get("period", "")
                actual = pt.get("actual_ppm")
                target = pt.get("target_ppm", 2000)
                var = pt.get("variance")
                exceeded = pt.get("is_exceeded", False)
                status_str = "EXCEEDED" if exceeded else "WITHIN TARGET"
                if actual is None:
                    status_str = "WITHHELD (CONFLICT)"

                ws_sum.write_string(curr_row, 0, str(period), cell_fmt)
                if actual is not None:
                    ws_sum.write_number(curr_row, 1, float(actual), num_fmt)
                else:
                    ws_sum.write_string(curr_row, 1, "N/A", cell_fmt)
                ws_sum.write_number(curr_row, 2, float(target), num_fmt)
                if var is not None:
                    ws_sum.write_number(curr_row, 3, float(var), num_fmt)
                else:
                    ws_sum.write_string(curr_row, 3, "N/A", cell_fmt)
                ws_sum.write_string(curr_row, 4, status_str, cell_fmt)
                curr_row += 1
            curr_row += 1

        elif w_type == "defect_pareto":
            ws_sum.write_row(curr_row, 0, ["Rank", "Defect Description", "Rejection Qty", "Cumulative %", "80% Zone"], header_fmt)
            curr_row += 1
            items = w.get("items", [])
            for idx, item in enumerate(items[:20]):
                desc = sanitize_for_spreadsheet(item.get("defect", ""))
                qty = float(item.get("rejections", 0))
                cum_pct = float(item.get("cumulative_percent", 0)) / 100.0
                zone = "Vital Few (≤80%)" if cum_pct <= 0.80 else "Useful Many (>80%)"

                ws_sum.write_number(curr_row, 0, idx + 1, cell_fmt)
                ws_sum.write(curr_row, 1, desc, cell_fmt)
                ws_sum.write_number(curr_row, 2, qty, num_fmt)
                ws_sum.write_number(curr_row, 3, cum_pct, pct_fmt)
                ws_sum.write_string(curr_row, 4, zone, cell_fmt)
                curr_row += 1
            curr_row += 1

        elif w_type == "model_comparison":
            ws_sum.write_row(curr_row, 0, ["Model", "Total Rejections", "Period Breakdown"], header_fmt)
            curr_row += 1
            for s in w.get("series", []):
                model_name = sanitize_for_spreadsheet(s.get("name", ""))
                tot = float(s.get("total", 0))
                breakdown = ", ".join(f"{v}" for v in s.get("period_data", []))
                ws_sum.write(curr_row, 0, model_name, cell_fmt)
                ws_sum.write_number(curr_row, 1, tot, num_fmt)
                ws_sum.write_string(curr_row, 2, breakdown, cell_fmt)
                curr_row += 1
            curr_row += 1

        elif w_type == "action_tracker":
            ws_sum.write_row(curr_row, 0, ["Action ID", "Status", "Champion / Owner", "Due Date", "Closure Date", "Overdue"], header_fmt)
            curr_row += 1
            for act in w.get("action_items", [])[:30]:
                aid = sanitize_for_spreadsheet(act.get("id", ""))
                astatus = sanitize_for_spreadsheet(act.get("status", "").upper())
                owner = sanitize_for_spreadsheet(act.get("owner", "Unassigned"))
                due = str(act.get("due_date") or "")
                close = str(act.get("closure_date") or "")
                overdue = "YES" if act.get("is_overdue") else "NO"

                ws_sum.write(curr_row, 0, aid, cell_fmt)
                ws_sum.write(curr_row, 1, astatus, cell_fmt)
                ws_sum.write(curr_row, 2, owner, cell_fmt)
                ws_sum.write_string(curr_row, 3, due, cell_fmt)
                ws_sum.write_string(curr_row, 4, close, cell_fmt)
                ws_sum.write_string(curr_row, 5, overdue, cell_fmt)
                curr_row += 1
            curr_row += 1

    # --- Sheet 2: Dashboard Spec ---
    ws_spec = workbook.add_worksheet("Dashboard Spec")
    ws_spec.set_tab_color("#64748b")
    ws_spec.set_column(0, 0, 24)
    ws_spec.set_column(1, 1, 18)
    ws_spec.set_column(2, 2, 28)
    ws_spec.set_column(3, 6, 20)

    ws_spec.write(0, 0, "Manufacturing Dashboard Specification", title_fmt)
    ws_spec.write(1, 0, "Technical specification, query bindings and metric provenance", meta_val_fmt)

    spec_headers = ["Widget ID", "Widget Type", "Title", "Dimensions", "Measures", "Source Sheet", "Provenance Status"]
    ws_spec.write_row(3, 0, spec_headers, header_fmt)
    s_row = 4

    for rw in data.get("raw_specs", []):
        wid = rw.get("widget_id", "")
        wtype = rw.get("widget_type", "")
        wtitle = rw.get("title", "")
        dims = ", ".join(rw.get("dimensions", []))
        meas = ", ".join(rw.get("measures", []))
        prov = rw.get("provenance", {})
        src_sheet = f"{prov.get('sheet_name', '')}!{prov.get('cell_range', '')}"
        conf = prov.get("confirmation_status", "confirmed")

        ws_spec.write(s_row, 0, wid, cell_fmt)
        ws_spec.write(s_row, 1, wtype, cell_fmt)
        ws_spec.write(s_row, 2, wtitle, cell_fmt)
        ws_spec.write(s_row, 3, dims, cell_fmt)
        ws_spec.write(s_row, 4, meas, cell_fmt)
        ws_spec.write(s_row, 5, src_sheet, cell_fmt)
        ws_spec.write(s_row, 6, conf, cell_fmt)
        s_row += 1

    # --- Sheet 3+: Normalized Datasets ---
    for idx, table in enumerate(data.get("dataset_tables", [])):
        sheet_title = f"Data_{table.get('sheet_name', f'Table{idx+1}')}"[:31]
        ws_data = workbook.add_worksheet(sheet_title)
        ws_data.set_tab_color("#10b981")

        cols = table.get("columns", [])
        rows = table.get("rows", [])

        # Write columns header
        for col_idx, col_name in enumerate(cols):
            ws_data.set_column(col_idx, col_idx, 16)
            ws_data.write(0, col_idx, str(col_name), header_fmt)

        # Write data rows with formula injection mitigation
        for r_idx, r_dict in enumerate(rows[:50000]):
            for c_idx, col_name in enumerate(cols):
                val = r_dict.get(col_name)
                # Sanitize formula triggers
                sanitized_val = sanitize_for_spreadsheet(val)
                if isinstance(sanitized_val, (int, float)):
                    ws_data.write_number(r_idx + 1, c_idx, sanitized_val, cell_fmt)
                elif sanitized_val is None:
                    ws_data.write_blank(r_idx + 1, c_idx, None, cell_fmt)
                else:
                    ws_data.write(r_idx + 1, c_idx, str(sanitized_val), cell_fmt)

    workbook.close()
    return os.path.getsize(output_path)


