class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas to compute total page count and draw running headers/footers."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states: List[Dict[str, Any]] = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count: int):
        self.saveState()
        self.setFont("Helvetica-Bold", 8)
        self.setFillColor(colors.HexColor("#0f172a"))
        w, h = self._pagesize

        # Running Top Header
        self.drawString(36, h - 24, "AUTOMATED MANUFACTURING QUALITY REPORT")
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748b"))
        self.drawRightString(w - 36, h - 24, "CONFIDENTIAL & PROPRIETARY")

        self.setStrokeColor(colors.HexColor("#cbd5e1"))
        self.setLineWidth(0.75)
        self.line(36, h - 28, w - 36, h - 28)

        # Running Bottom Footer
        self.line(36, 28, w - 36, 28)
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748b"))
        self.drawString(36, 16, "Generated by Local-First Business Reporting Engine • Metric Provenance Verified")
        self.drawRightString(w - 36, 16, f"Page {self._pageNumber} of {page_count}")
        self.restoreState()


