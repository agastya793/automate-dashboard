# ---------------------------------------------------------------------------
# Core Orchestration Function
# ---------------------------------------------------------------------------

def generate_export(
    db: Session,
    export_id: str,
    storage: StorageBackend,
) -> Dict[str, Any]:
    """
    Orchestrates the end-to-end generation of an authorized export:
    1. Loads Export record and verifies state.
    2. Updates status to 'processing'.
    3. Prepares verified dashboard data.
    4. Generates file to an atomic temporary path.
    5. Saves output object to private local storage.
    6. Updates export record with 'ready' status and size in bytes.
    7. Cleans up temporary artifacts on completion or failure.
    """
    export_uuid = uuid.UUID(str(export_id))
    export_repo = ExportRepository(db)
    export_record = export_repo.get(export_uuid)

    if not export_record:
        logger.error(f"Export '{export_id}' not found in database.")
        return {"status": "error", "message": f"Export '{export_id}' not found."}

    if export_record.status in ("ready", "completed"):
        logger.info(f"Export '{export_id}' is already ready.")
        return {"status": "ready", "export_id": export_id}

    # Mark as processing
    export_repo.update_status(export_uuid, status="processing")
    fmt = (export_record.format or "").lower().strip()

    # Setup atomic temp path
    with tempfile.NamedTemporaryFile(suffix=f".{fmt}", delete=False) as tmp_file:
        tmp_path = tmp_file.name

    try:
        data = prepare_dashboard_export_data(
            db=db,
            dashboard_id=str(export_record.dashboard_id),
            filters=export_record.options.get("filters") if export_record.options else None,
            storage=storage,
        )

        if fmt == "pdf":
            file_size = generate_pdf_export(data, tmp_path, export_record.options)
        elif fmt == "xlsx":
            file_size = generate_excel_export(data, tmp_path, export_record.options)
        elif fmt == "csv":
            file_size = generate_csv_export(data, tmp_path, export_record.options)
        elif fmt == "png":
            file_size = generate_png_export(data, tmp_path, export_record.options)
        else:
            raise ValueError(f"Unsupported export format '{fmt}'.")

        # Save generated file to private storage key atomically
        with open(tmp_path, "rb") as f:
            output_bytes = f.read()

        storage_key = export_record.storage_key or f"exports/{export_id}/report.{fmt}"
        storage.put_object(storage_key, output_bytes)

        # Mark ready
        export_repo.update_status(
            export_uuid,
            status="ready",
            file_size_bytes=len(output_bytes),
        )
        logger.info(f"Export '{export_id}' successfully generated ({len(output_bytes)} bytes).")
        return {
            "status": "ready",
            "export_id": export_id,
            "format": fmt,
            "size_bytes": len(output_bytes),
        }

    except Exception as exc:
        logger.exception(f"Export generation failed for '{export_id}': {exc}")
        safe_msg = f"Export generation failed: {str(exc)}"
        export_repo.update_status(
            export_uuid,
            status="failed",
            error_code="EXPORT_GENERATION_FAILED",
            error_message=safe_msg,
        )
        return {"status": "failed", "export_id": export_id, "error": safe_msg}

    finally:
        # Guarantee cleanup of temporary file
        if os.path.exists(tmp_path):
            try:
                os.remove(tmp_path)
            except OSError:
                pass
