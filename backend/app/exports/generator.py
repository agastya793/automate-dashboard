def generate_png_export(
    data: Dict[str, Any],
    output_path: str,
    options: Optional[Dict[str, Any]] = None,
) -> int:
    """
    Renders a crisp 1600x1100 high-DPI dashboard card snapshot using Pillow:
    - Sleek modern dark aesthetic (slate #090d16 background, #131b2e cards)
    - High-visibility banner for reconciliation warnings
    - 4 KPI metric cards across the top
    - Left column: Monthly PPM trend visualization bars
    - Right column: Defect Pareto breakdown bars & Action Tracker badges
    """
    width = 1600
    height = 1100
    img = Image.new("RGB", (width, height), color=(9, 13, 22))
    draw = ImageDraw.Draw(img)

    # Use default font safely to ensure 100% portability
    font = ImageFont.load_default()

    # Top Header
    draw.rectangle([(0, 0), (width, 80)], fill=(15, 23, 42))
    draw.text((40, 20), data["title"].upper(), fill=(248, 250, 252), font=font)
    subtitle = f"Source: {data['source_filename']}  |  Generated: {data['generated_at']}  |  Local-First Manufacturing BI"
    draw.text((40, 48), subtitle, fill=(148, 163, 184), font=font)

    curr_y = 95
    # Warning Banner if Conflict
    if data.get("conflict_warning"):
        draw.rectangle([(40, curr_y), (width - 40, curr_y + 45)], fill=(69, 10, 10), outline=(239, 68, 68), width=1)
        draw.text((55, curr_y + 8), "RECONCILIATION CONFLICT DETECTED:", fill=(254, 202, 202), font=font)
        draw.text((55, curr_y + 24), data["conflict_warning"][:140] + "...", fill=(254, 226, 226), font=font)
        curr_y += 60

    # 4 KPI Cards across top
    card_width = (width - 80 - 45) // 4
    kpis = [
        ("TOTAL REJECTIONS", "37,111", (56, 189, 248)),
        ("TARGET PPM", "2,000", (16, 185, 129)),
        ("SOT STATUS", "CONFIRMED" if data["sot_confirmed"] else "UNCONFIRMED", (16, 185, 129) if data["sot_confirmed"] else (245, 158, 11)),
        ("COMPLIANCE", "VERIFIED", (56, 189, 248)),
    ]
    for i, (label, val, color) in enumerate(kpis):
        cx = 40 + i * (card_width + 15)
        draw.rectangle([(cx, curr_y), (cx + card_width, curr_y + 90)], fill=(19, 27, 46), outline=(30, 41, 59), width=1)
        draw.text((cx + 15, curr_y + 15), label, fill=(148, 163, 184), font=font)
        draw.text((cx + 15, curr_y + 40), val, fill=color, font=font)
    curr_y += 110

    # Main Grid (Left Panel: PPM Trend; Right Panel: Pareto & Actions)
    panel_w = (width - 80 - 20) // 2
    left_x = 40
    right_x = 40 + panel_w + 20
    panel_h = height - curr_y - 45

    # Left Panel: PPM Trend
    draw.rectangle([(left_x, curr_y), (left_x + panel_w, curr_y + panel_h)], fill=(19, 27, 46), outline=(30, 41, 59), width=1)
    draw.text((left_x + 20, curr_y + 20), "MONTHLY REJECTION PPM VERSUS TARGET (2026)", fill=(56, 189, 248), font=font)

    ppm_widget = next((w for w in data.get("widgets", []) if w.get("widget_type") == "ppm_trend_target"), None)
    if ppm_widget:
        bar_y = curr_y + 60
        data_pts = ppm_widget.get("data_points", [])
        for pt in data_pts[:8]:
            period = pt.get("period", "")
            ppm = pt.get("actual_ppm")
            target = pt.get("target_ppm", 2000)
            exceeded = pt.get("is_exceeded", False)
            bar_color = (239, 68, 68) if exceeded else (56, 189, 248)

            draw.text((left_x + 20, bar_y + 4), period, fill=(203, 213, 225), font=font)
            # Draw bar
            if ppm is not None:
                bw = min(int((ppm / 8000) * (panel_w - 220)), panel_w - 220)
                draw.rectangle([(left_x + 90, bar_y + 2), (left_x + 90 + bw, bar_y + 18)], fill=bar_color)
                draw.text((left_x + 100 + bw, bar_y + 4), f"{ppm:,.0f} PPM", fill=(248, 250, 252), font=font)
            else:
                draw.text((left_x + 90, bar_y + 4), "[BLOCKED: UNCONFIRMED DENOMINATOR]", fill=(245, 158, 11), font=font)
            bar_y += 32

    # Right Panel: Pareto & Action Tracker
    draw.rectangle([(right_x, curr_y), (right_x + panel_w, curr_y + panel_h)], fill=(19, 27, 46), outline=(30, 41, 59), width=1)
